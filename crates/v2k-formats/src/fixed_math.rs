/// Reconstruct one signed Q15 sine exactly as the retail lookup sites do.
///
/// The angle is the engine's wrapping 16-bit domain (full turn = `0x10000`).
/// Its low two bits are deliberately discarded because the executable masks a
/// byte offset before dividing by four to index the word table.
pub fn retail_sine_q15(angle: u32) -> i32 {
    let mut folded = angle & 0x3ffc;
    if angle & 0x4000 != 0 {
        folded = 0x3ffc - folded;
    }
    let value = i32::from(RETAIL_QUARTER_SINE[(folded >> 2) as usize]);
    if angle & 0x8000 != 0 {
        -value
    } else {
        value
    }
}

/// Exact unsigned-word model sine product used by DD/ED register commands.
///
/// `466870`/`466900` duplicate the positive quarter-table word into both halves
/// of a Q31 dword, then negate the whole dword for the negative half-cycle.
/// Signed IMUL followed by SHL EAX/RCL EDX publishes product bits31..46. This
/// deliberately differs from floating sine and from duplicating a signed Q15
/// value. Cosine supplies its wrapping quarter-turn before entering this helper.
pub fn retail_model_sine_product(amplitude: u16, angle: u16) -> u16 {
    let quarter = retail_sine_q15(u32::from(angle & 0x7fff)) as u32;
    let repeated = ((quarter << 16) | quarter) as i32;
    let sine_q31 = if angle & 0x8000 != 0 {
        repeated.wrapping_neg()
    } else {
        repeated
    };
    ((i64::from(sine_q31) * i64::from(amplitude)) >> 31) as u16
}

/// Exact retail integer-square-root helper returned by `FUN_00457730`.
///
/// The executable accepts a signed 32-bit operand and returns zero for every
/// non-positive value. Positive inputs use the original 16-step restoring
/// algorithm, including its signed comparison after wrapping candidate
/// arithmetic. Values at or above `0x4000_0000` therefore produce retail's
/// `0xFFFF`, not the ordinary mathematical floor square root.
pub fn retail_integer_sqrt(value: i32) -> u32 {
    if value < 1 {
        return 0;
    }

    let mut result = 0x8000_u32;
    let mut remainder = 0x4000_0000_i32;
    let mut bit = 15_u32;

    if value < 0x4000_0000 {
        loop {
            result >>= 1;
            remainder >>= 2;
            bit = bit.wrapping_sub(1);
            if value >= remainder {
                break;
            }
        }
    }

    let mut candidate_bit = result >> 1;
    if candidate_bit != 0 {
        let mut square_shift = bit.wrapping_sub(1).wrapping_mul(2);
        loop {
            let candidate = 1_i32
                .wrapping_shl(square_shift & 0x1f)
                .wrapping_add(remainder)
                .wrapping_add((result << (bit & 0x1f)) as i32);
            if candidate <= value {
                result = result.wrapping_add(candidate_bit);
                remainder = candidate;
            }
            candidate_bit >>= 1;
            bit = bit.wrapping_sub(1);
            square_shift = square_shift.wrapping_sub(2);
            if candidate_bit == 0 {
                break;
            }
        }
    }
    result
}

/// Exact retail inverse sine returned by `FUN_00457F70`.
///
/// The operand is a signed Q31 ratio and the result a signed angle in the
/// engine's 16-bit domain (`0x4000` = 90 degrees). The executable indexes the
/// 1,024-word table at VA `0x004D34D0` with the magnitude shifted right by 21
/// and restores the sign afterwards. Callers never pass `i32::MIN`; its index
/// is clamped to the last entry instead of reading before the table.
pub fn retail_arcsine_q31(ratio_q31: i32) -> i32 {
    let index = ((ratio_q31.unsigned_abs() >> 21) as usize).min(RETAIL_ARCSINE_ENTRIES - 1);
    let angle = i32::from(retail_arcsine_table()[index]);
    if ratio_q31 < 0 {
        -angle
    } else {
        angle
    }
}

const RETAIL_ARCSINE_ENTRIES: usize = 1024;

/// Frontier's table generator divided by five-digit pi, not `PI`.
#[allow(clippy::approx_constant)]
const RETAIL_ARCSINE_GENERATOR_PI: f64 = 3.14159;

/// The retail table is `floor(asin(i / 1024) / 3.14159 * 32768)`: Frontier's
/// generator used five-digit pi, which leaves two entries one above the
/// exact-pi floor. The closest entry is 5.2e-4 from an integer boundary, so
/// every libm generates the same words.
fn retail_arcsine_table() -> &'static [i16; RETAIL_ARCSINE_ENTRIES] {
    static TABLE: std::sync::OnceLock<[i16; RETAIL_ARCSINE_ENTRIES]> = std::sync::OnceLock::new();
    TABLE.get_or_init(|| {
        let mut table = [0; RETAIL_ARCSINE_ENTRIES];
        for (index, entry) in table.iter_mut().enumerate() {
            let ratio = index as f64 / RETAIL_ARCSINE_ENTRIES as f64;
            *entry = (ratio.asin() / RETAIL_ARCSINE_GENERATOR_PI * 32768.0).floor() as i16;
        }
        table
    })
}

