//! Retail V2000 particle-class descriptor data.
//!
//! The executable stores 96 records at `0x004CC138`, each exactly `0x34`
//! bytes. The next byte at `0x004CD4B8` begins the unrelated 100-vector
//! displacement table, proving that the older 128-record interpretation
//! overran the descriptor array by 32 entries.
//!
//! Every descriptor dword is retained verbatim. Accessors below name only
//! fields whose use is directly established by `FUN_00440A60`,
//! `FUN_0043D410`, and the common particle update loop. Callback/data words
//! remain available through `raw_words` without speculative semantics.

/// Retail virtual address of particle descriptor class zero.
pub const PARTICLE_DESCRIPTOR_TABLE_VA: u32 = 0x004C_C138;
/// Exact size of one retail descriptor.
pub const PARTICLE_DESCRIPTOR_STRIDE: usize = 0x34;
/// Exact number of descriptors before the next static table.
pub const PARTICLE_DESCRIPTOR_COUNT: usize = 96;
/// First byte after the descriptor table.
pub const PARTICLE_DESCRIPTOR_END_VA: u32 =
    PARTICLE_DESCRIPTOR_TABLE_VA + (PARTICLE_DESCRIPTOR_COUNT * PARTICLE_DESCRIPTOR_STRIDE) as u32;
/// Retail address of the unrelated 100-entry displacement table.
pub const PARTICLE_DIRECTION_TABLE_VA: u32 = 0x004C_D4B8;

const PARTICLE_FRAME_DATA_BASE_VA: u32 = 0x004C_B508;
const PARTICLE_FRAME_DATA_END_VA: u32 = 0x004C_BF52;
const PARTICLE_FRAME_WORD_COUNT: usize =
    ((PARTICLE_FRAME_DATA_END_VA - PARTICLE_FRAME_DATA_BASE_VA) / 2) as usize;

/// One lossless 0x34-byte descriptor, represented as the executable's 13
/// little-endian dwords.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ParticleDescriptor {
    raw_words: [u32; PARTICLE_DESCRIPTOR_STRIDE / 4],
}

impl ParticleDescriptor {
    pub const fn from_raw_words(raw_words: [u32; PARTICLE_DESCRIPTOR_STRIDE / 4]) -> Self {
        Self { raw_words }
    }

    pub const fn raw_words(&self) -> &[u32; PARTICLE_DESCRIPTOR_STRIDE / 4] {
        &self.raw_words
    }

    pub const fn raw_byte(&self, offset: usize) -> u8 {
        let word = self.raw_words[offset / 4];
        ((word >> ((offset % 4) * 8)) & 0xff) as u8
    }

    pub const fn raw_u16(&self, offset: usize) -> u16 {
        u16::from_le_bytes([self.raw_byte(offset), self.raw_byte(offset + 1)])
    }

    pub const fn raw_u32(&self, offset: usize) -> u32 {
        u32::from_le_bytes([
            self.raw_byte(offset),
            self.raw_byte(offset + 1),
            self.raw_byte(offset + 2),
            self.raw_byte(offset + 3),
        ])
    }

    /// Absolute retail VA of the first 6-byte frame tuple, or zero.
    pub const fn frame_list_va(&self) -> u32 {
        self.raw_u32(0)
    }

    /// Number of 6-byte frame tuples (`descriptor + 0x06`).
    pub const fn frame_count(&self) -> u8 {
        self.raw_byte(0x06)
    }

    /// Particle presentation/control flags (`descriptor + 0x07`).
    pub const fn flags(&self) -> u8 {
        self.raw_byte(0x07)
    }

    /// Frame multiplier used by `((rate * age_tick) >> 6) % frame_count`.
    pub const fn animation_rate_raw(&self) -> u8 {
        self.raw_byte(0x08)
    }

    /// Class draw scale passed to the particle sprite renderer.
    pub const fn draw_scale_raw(&self) -> u16 {
        self.raw_u16(0x0a)
    }

    /// Divisor for the pool-slot size variation term.
    pub const fn size_jitter_divisor_raw(&self) -> u8 {
        self.raw_byte(0x0c)
    }

    /// Strict common-update expiry threshold in retail 50-Hz ticks.
    pub const fn lifetime_ticks(&self) -> u16 {
        self.raw_byte(0x0d) as u16
    }

    /// Signed intrusive-list priority consumed by `FUN_00440A60`.
    ///
    /// Priority zero is the fixed pool's free list; authored live particles
    /// occupy lists 1 through 6. Negative priorities reject the allocation.
    pub const fn priority_raw(&self) -> i8 {
        self.raw_byte(0x0f) as i8
    }

    /// Signed-word collision/presentation radius at `descriptor + 0x10`.
    pub const fn collision_radius_raw(&self) -> u16 {
        self.raw_u16(0x10)
    }

    /// Signed painter-order bias added to projected depth by `FUN_0043D410`
    /// (`descriptor + 0x12`).
    pub const fn sort_bias_raw(&self) -> i16 {
        self.raw_u16(0x12) as i16
    }

    /// Signed Y-position bias added to the caller's word by
    /// `FUN_00440A60` (`descriptor + 0x28`), before water classification.
    pub const fn spawn_position_y_bias_raw(&self) -> i16 {
        self.raw_u16(0x28) as i16
    }

    /// Signed Y-velocity bias added to the caller's spawn argument by
    /// `FUN_00440A60` (`descriptor + 0x2A`).
    pub const fn spawn_velocity_y_bias_raw(&self) -> i16 {
        self.raw_u16(0x2a) as i16
    }
}

